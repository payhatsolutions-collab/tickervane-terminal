// Compact tuples avoid repeating object keys and the default sector thousands
// of times in the startup bundle, while preserving the public object interface.
export function stockDirectorySource(stocks, updatedAt) {
  const rows = stocks.map(({ symbol, name, sector }) =>
    JSON.stringify(sector === 'Others' ? [symbol, name] : [symbol, name, sector]));
  return `// Generated by scripts/refresh-stock-directory.mjs — do not edit by hand.
// NSE mainboard + SME directory; legacy entries and curated sectors retained.
// Prices and history load separately from the market API.
export const stockDirectoryUpdatedAt = ${JSON.stringify(updatedAt)};

export const stockDirectory = [
${rows.map(row => `  ${row},`).join('\n')}
].map(([symbol, name, sector = 'Others']) => ({ symbol, name, sector }));
`;
}
